const modal = document.querySelector('.gallery');
const grid = document.querySelector('.gallery-grid');

function preencherGaleria(id) {
  const evento = galerias[id];

  if (!evento) return;

  modal.querySelector('.gallery-heading h2').textContent = evento.titulo;
  modal.querySelector('.gallery-heading p').textContent = evento.ano;

  const imagens = evento.fotos.map((src, index) => {
    const img = document.createElement('img');
    img.src = src;
    img.alt = `${evento.titulo} — foto ${index + 1}`;
    img.loading = 'lazy';
    img.addEventListener('error', () => img.remove());

    return img;
  });

  grid.replaceChildren(...imagens);

  if (!modal.open) {
    modal.showModal();
  }

  document.body.classList.add('modal-open');
  modal.scrollTop = 0;
}

function abrirGaleria(id) {
  if (!galerias[id] || modal.open) return;

  history.pushState({ galeria: id }, '', `#galeria-${id}`);
  preencherGaleria(id);
}

document.querySelectorAll('.event-card').forEach(card => {
  card.querySelectorAll('button').forEach(button => {
    button.addEventListener('click', () => abrirGaleria(card.dataset.evento));
  });
});

function fecharGaleria() {
  if (!modal.open) return;

  if (history.state?.galeria) {
    history.back();
  } else {
    modal.close();
  }
}

modal.querySelector('.back-button').addEventListener('click', fecharGaleria);
modal.querySelector('.close-button').addEventListener('click', fecharGaleria);

modal.addEventListener('click', event => {
  if (event.target === modal) {
    fecharGaleria();
  }
});

modal.addEventListener('close', () => {
  document.body.classList.remove('modal-open');
});

window.addEventListener('popstate', event => {
  if (event.state?.galeria && galerias[event.state.galeria]) {
    preencherGaleria(event.state.galeria);
  } else if (modal.open) {
    modal.close();
  }
});

const menuButton = document.querySelector('.menu-button');
const mobileMenu = document.querySelector('.mobile-menu');

function fecharMenuMobile() {
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', 'Abrir menu');
  mobileMenu.classList.remove('open');
}

menuButton.addEventListener('click', () => {
  const aberto = menuButton.getAttribute('aria-expanded') === 'true';
  menuButton.setAttribute('aria-expanded', String(!aberto));
  menuButton.setAttribute('aria-label', aberto ? 'Abrir menu' : 'Fechar menu');
  mobileMenu.classList.toggle('open', !aberto);
});

mobileMenu.querySelectorAll('a').forEach(link => {
  link.addEventListener('click', fecharMenuMobile);
});

const navLinks = document.querySelectorAll('.nav-left a, .mobile-menu a[href^="#"]');
const sections = document.querySelectorAll('#inicio, #depoimentos, #sobre');

function atualizarNavegacaoAtiva() {
  const linhaAtivacao = window.innerHeight * 0.28;
  let secaoAtiva = 'inicio';

  sections.forEach(section => {
    if (section.getBoundingClientRect().top <= linhaAtivacao) {
      secaoAtiva = section.id;
    }
  });

  if (window.scrollY + window.innerHeight >= document.documentElement.scrollHeight - 4) {
    secaoAtiva = 'sobre';
  }

  navLinks.forEach(link => {
    link.classList.toggle('active', link.hash === `#${secaoAtiva}`);
  });
}

window.addEventListener('scroll', atualizarNavegacaoAtiva, { passive: true });
window.addEventListener('resize', atualizarNavegacaoAtiva);
atualizarNavegacaoAtiva();